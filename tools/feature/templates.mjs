export function e2e({ t, softDelete }) {
  const path = `/v1/${t.plural}`;
  const audit = lowerFirst(t.Singular);
  return [
    `import { randomUUID } from 'node:crypto';`,
    `import type request from 'supertest';`,
    `import { ${t.SINGULAR} } from '../src/features/${t.plural}/${t.singular}.record.js';`,
    `import { fieldSamples } from '../src/platform/fields/fields.js';`,
    `import { describeCapabilities } from './record-capabilities.js';`,
    `import { bootApp, type TestApp } from './support.js';`,
    '',
    `/**`,
    ` * ${pascalOf(t.nouns)}: the standard routes, on bodies from the declaration (fieldSamples):`,
    ` * a field added later is covered. ${GENERATED("add the feature's own rules as tests here.")}`,
    ` */`,
    `describe('${t.nouns} (e2e)', () => {`,
    `  let node: TestApp;`,
    '',
    `  beforeEach(async () => {`,
    `    node = await bootApp();`,
    `  });`,
    `  afterEach(() => node.close());`,
    '',
    `  const samples = fieldSamples(${t.SINGULAR}.fields);`,
    `  /** A change of one field. */`,
    `  const changed = samples.changed;`,
    `  const create = (agent: request.Agent, key = randomUUID(), sent = samples.body()) =>`,
    `    agent.post('${path}').set('Idempotency-Key', key).send(sent);`,
    '',
    `  it('creates once per Idempotency-Key, changes with If-Match (audited), deletes', async () => {`,
    `    const admin = node.admin();`,
    `    const key = randomUUID();`,
    `    const sent = samples.body();`,
    `    const created = await create(admin, key, sent).expect(201);`,
    `    const id = created.body.id as string;`,
    `    // The same key again: the first answer, not a second record.`,
    `    expect((await create(admin, key, sent)).body.id).toBe(id);`,
    '',
    `    const shown = await admin.get(\`${path}/\${id}\`).expect(200);`,
    `    const etag = shown.headers.etag as string;`,
    `    const updated = await admin.patch(\`${path}/\${id}\`).set('If-Match', etag).send(changed).expect(200);`,
    `    expect(updated.body[samples.changedField]).toEqual(changed[samples.changedField]);`,
    `    // The ETag read before the change no longer matches.`,
    `    await admin.patch(\`${path}/\${id}\`).set('If-Match', etag).send(changed).expect(412);`,
    `    const actions = (await node.auditEntries({ targetId: id })).map((entry) => entry.action);`,
    `    expect(actions).toEqual(expect.arrayContaining(['${audit}.created', '${audit}.updated']));`,
    '',
    `    await admin.delete(\`${path}/\${id}\`).expect(204);`,
    `    await admin.get(\`${path}/\${id}\`).expect(404);`,
    ...(softDelete
      ? [
          `    // The recycle bin: back until the purge.`,
          `    await admin.post(\`${path}/\${id}/restore\`).expect(200);`,
          `    await admin.get(\`${path}/\${id}\`).expect(200);`,
        ]
      : []),
    `  });`,
    '',
    `  it('refuses a body that fails the schema', async () => {`,
    `    await node.admin().post('${path}').set('Idempotency-Key', randomUUID()).send({ ...samples.body(), ...samples.invalid }).expect(400);`,
    `  });`,
    '',
    `  it('lets each role do what it grants: editors their own, viewers read', async () => {`,
    `    const writer = await node.user(['editor']);`,
    `    const other = await node.user(['editor']);`,
    `    const viewer = await node.user(['viewer']);`,
    `    const id = (await create(writer.agent).expect(201)).body.id as string;`,
    `    await other.agent.get(\`${path}/\${id}\`).expect(403);`,
    `    expect((await other.agent.get('${path}').expect(200)).body.items).toEqual([]);`,
    `    await viewer.agent.get(\`${path}/\${id}\`).expect(200);`,
    `    await create(viewer.agent).expect(403);`,
    `  });`,
    '',
    `  it('keeps tenants apart', async () => {`,
    `    const id = (await create(node.admin()).expect(201)).body.id as string;`,
    `    const other = await node.otherTenant();`,
    `    await other.admin.get(\`${path}/\${id}\`).expect(404);`,
    `  });`,
    '',
    `  it('lists newest first', async () => {`,
    `    const admin = node.admin();`,
    `    await create(admin).expect(201);`,
    `    const newest = (await create(admin).expect(201)).body.id as string;`,
    `    const page = await admin.get('${path}?sort=-createdAt&limit=10').expect(200);`,
    `    expect(page.body.items[0].id).toBe(newest);`,
    `    expect(page.body.items).toHaveLength(2);`,
    `  });`,
    '',
    `  // Each capability ${t.singular}.record.ts declares (record-capabilities.ts).`,
    `  describeCapabilities(() => node, ${t.SINGULAR});`,
    `});`,
  ].join('\n');
}
