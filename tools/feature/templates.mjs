export function policy({ t, softDelete, team }) {
  const S = t.Singular;
  const read = team ? `['mine', 'inMyTeams']` : `['mine']`;
  const actions = [
    'read',
    'create',
    'update',
    'delete',
    ...(softDelete ? ['restore'] : []),
  ];
  const own = (action) =>
    action === 'create'
      ? `{ subject: '${S}', action: 'create', conditions: [] }`
      : `{ subject: '${S}', action: '${action}', conditions: [{ key: 'mine' }] }`;
  const fieldsType = [
    'ownerId',
    ...(team ? ['teamId'] : []),
    ...(softDelete ? ['deletedAt'] : []),
  ];
  return [
    `import { Policy } from '@nestjs/authorization';`,
    `import { AccessService } from '../../iam/access/access.service.js';`,
    `import { createdBy, definePermissions${team ? ', inMyTeams' : ''} } from '../../iam/access/permissions.js';`,
    `import type { Principal } from '../../iam/auth/principal.js';`,
    `import { recordPermissionFields } from '../../platform/records/record.js';`,
    `import { ${t.SINGULAR} } from './${t.singular}.record.js';`,
    `import type { ${S} } from './${t.singular}.schemas.js';`,
    `import { ${t.pluralCamel} } from './${t.plural}.tables.js';`,
    '',
    `/**`,
    ` * What can be done with ${t.nouns}, and the conditions an administrator may attach`,
    ` * (GET /v1/access/catalog). ${GENERATED('add fields (field-level permissions) and conditions as the feature needs.')}`,
    ` */`,
    `export const ${t.SINGULAR}_PERMISSIONS = definePermissions({`,
    `  subjects: {`,
    `    ${S}: {`,
    `      label: '${pascalOf(t.nouns)}',`,
    `      // Field-level permissions: those of the record's capabilities (custom), and its own fields.`,
    `      fields: { ...recordPermissionFields(${t.SINGULAR}) },`,
    `      conditions: {`,
    `        mine: createdBy('ownerId', ${t.pluralCamel}.ownerId),`,
    ...(team
      ? [`        inMyTeams: inMyTeams('teamId', ${t.pluralCamel}.teamId),`]
      : []),
    `      },`,
    `      actions: {`,
    `        read: { label: 'See ${t.nouns}', conditions: ${read} },`,
    `        create: { label: 'Create ${t.nouns}', conditions: [] },`,
    `        update: { label: 'Change ${t.nouns}', conditions: ['mine'] },`,
    `        delete: { label: 'Delete ${t.nouns}', conditions: ['mine'] },`,
    ...(softDelete
      ? [
          `        restore: { label: 'See deleted ${t.nouns} and restore them', conditions: ${read} },`,
        ]
      : []),
    `      },`,
    `    },`,
    `  },`,
    `  // What every API client may do, on top of its roles: its own ${t.nouns}.`,
    `  clientPermissions: [`,
    ...actions.map((action) => `    ${own(action)},`),
    `  ],`,
    `  // Added to the roles every tenant starts with (same key: merged with the other features').`,
    `  seedRoles: [`,
    `    {`,
    `      key: 'editor',`,
    `      name: 'Editor',`,
    `      description: 'Writes records and changes their own.',`,
    `      permissions: [`,
    ...actions.map((action) => `        ${own(action)},`),
    `      ],`,
    `    },`,
    `    {`,
    `      key: 'viewer',`,
    `      name: 'Viewer',`,
    `      description: 'Sees every record, changes nothing.',`,
    `      permissions: [{ subject: '${S}', action: 'read', conditions: [] }],`,
    `    },`,
    `  ],`,
    `});`,
    '',
    `/** The fields of ${t.aNoun} its conditions read. */`,
    `type ${S}Fields = Pick<${S}, ${fieldsType.map((f) => `'${f}'`).join(' | ')}>;`,
    `const ${t.singularCamel}Fields = ({ ${fieldsType.join(', ')} }: ${S}Fields) => ({ ${fieldsType.join(', ')} });`,
    '',
    `@Policy()`,
    `export class ${S}Policy {`,
    `  constructor(private readonly access: AccessService) {}`,
    '',
    `  create(user: Principal | null) {`,
    `    return this.access.can(user, 'create', '${S}');`,
    `  }`,
    ...actions
      .filter((action) => action !== 'create')
      .flatMap((action) => [
        '',
        `  ${action}(user: Principal | null, ${t.singularCamel}: ${S}Fields) {`,
        `    return this.access.can(user, '${action}', '${S}', ${t.singularCamel}Fields(${t.singularCamel}));`,
        `  }`,
      ]),
    `}`,
  ].join('\n');
}

export function service({ t, fields, softDelete, team }) {
  const S = t.Singular;
  const table = t.pluralCamel;
  const uniques = fields.filter((f) => f.unique);
  return [
    `import { ${uniques.length ? 'ConflictException, ' : ''}Injectable, NotFoundException } from '@nestjs/common';`,
    `import { TransactionHost } from '@nestjs-cls/transactional';`,
    `import { and, eq, getTableColumns, ${softDelete ? 'isNotNull, isNull, ' : ''}type SQL } from 'drizzle-orm';`,
    `import type { Database, Transaction } from '../../core/database/drizzle.js';`,
    ...(uniques.length
      ? [
          `import { pgErrorCode, UNIQUE_VIOLATION } from '../../core/database/errors.js';`,
        ]
      : []),
    `import { database, type DrizzleTransactions, inTransaction } from '../../core/database/transactions.js';`,
    `import { afterCursor, countPage, pageOffset, pageOrder, type PageQuery, toPage } from '../../core/http/pagination.js';`,
    ...(team
      ? [`import { TeamsService } from '../../iam/access/teams.service.js';`]
      : []),
    `import { AuditService } from '../../iam/audit/audit.service.js';`,
    `import { type Principal, principalKey } from '../../iam/auth/principal.js';`,
    `import { recordView } from '../../platform/records/record.js';`,
    `import { RecordLifecycle } from '../../platform/records/record-contract.js';`,
    `import { ${t.SINGULAR} } from './${t.singular}.record.js';`,
    `import { ${t.SINGULAR}_RESOURCE } from './${t.singular}.resource.js';`,
    `import type { Create${S}Dto, ${S}, Update${S}Dto } from './${t.singular}.schemas.js';`,
    `import { ${table} } from './${t.plural}.tables.js';`,
    '',
    `/**`,
    ` * ${pascalOf(t.nouns)}: the writes and the reads. Each write, its audit entry and what its`,
    ` * capabilities do (RecordLifecycle: watchers, revisions) commit in one transaction.`,
    ` * ${GENERATED('the business logic goes where the comments say "Business logic".')}`,
    ` */`,
    `@Injectable()`,
    `export class ${t.Plural}Service {`,
    `  constructor(`,
    `    private readonly txHost: TransactionHost<DrizzleTransactions>,`,
    `    private readonly audit: AuditService,`,
    `    private readonly lifecycle: RecordLifecycle,`,
    ...(team ? [`    private readonly teams: TeamsService,`] : []),
    `  ) {}`,
    '',
    `  /** The current transaction, or the database outside one (core/database/transactions.ts). */`,
    `  private get db() {`,
    `    return database(this.txHost);`,
    `  }`,
    '',
    `  /** A new one of \`owner\`'s; \`by\` is who acts, when not the owner (a system job). */`,
    `  async create(owner: Principal, dto: Create${S}Dto, { by = owner }: { by?: Principal } = {}): Promise<${S}> {`,
    `    // Business logic: check or derive values here, before the transaction.`,
    `    // The body as columns; custom values checked against their fields (RecordLifecycle).`,
    `    const values = await this.lifecycle.values(dto, 'create');`,
    `    return inTransaction(this.txHost, async (tx) => {`,
    `      const [row] = await tx`,
    `        .insert(${table})`,
    `        .values({`,
    `          ownerId: principalKey(owner),`,
    ...(team
      ? [
          `          // A user's record belongs to their (first) team.`,
          `          teamId: owner.kind === 'user' ? ((await this.teams.teamsOf(owner.id, tx))[0] ?? null) : null,`,
        ]
      : []),
    `          ...values,`,
    `        } as typeof ${table}.$inferInsert)`,
    `        .returning()${uniques.length ? '.catch(taken)' : ''};`,
    `      await this.lifecycle.created(tx, { row: row!, owner, by });`,
    `      // Business logic: what else happens with it, in this transaction (events, notifications).`,
    `      await this.audit.recordChange(by, ${t.SINGULAR}_RESOURCE, { action: 'created', id: row!.id, after: recordView(${t.SINGULAR}, row!) }, tx);`,
    `      return row!;`,
    `    });`,
    `  }`,
    '',
    `  /** One, or a 404${softDelete ? ' (deleted ones with `deleted`: the recycle bin)' : ''}. */`,
    `  async findOne(id: string, db: Database | Transaction = this.db${softDelete ? ', { deleted = false }: { deleted?: boolean } = {}' : ''}): Promise<${S}> {`,
    `    const [row] = await db`,
    `      .select()`,
    `      .from(${table})`,
    softDelete
      ? `      .where(and(eq(${table}.id, id), deleted ? isNotNull(${table}.deletedAt) : isNull(${table}.deletedAt)));`
      : `      .where(eq(${table}.id, id));`,
    `    if (!row) {`,
    `      throw new NotFoundException(\`${pascalOf(t.noun)} \${id} not found.\`);`,
    `    }`,
    `    return row;`,
    `  }`,
    '',
    `  /** A page of those matching \`where\` (the caller's read filter, from AccessService), newest first. */`,
    `  async findPage(`,
    `    where: SQL | undefined,`,
    `    query: PageQuery,`,
    `    /** Sort values that aren't columns (the search rank), for the cursor: the list's sortSelect(query). */`,
    `    extra: Record<string, SQL.Aliased> = {},`,
    `  ) {`,
    `    const [rows, total] = await Promise.all([`,
    `      this.db`,
    `        .select({ ...getTableColumns(${table}), ...extra })`,
    `        .from(${table})`,
    `        .where(and(where, afterCursor(${table}.id, query)))`,
    `        .orderBy(...pageOrder(${table}.id, query))`,
    `        .limit(query.limit + 1)`,
    `        .offset(pageOffset(query)),`,
    `      countPage(this.db, ${table}, where, query),`,
    `    ]);`,
    `    return toPage(rows, query, total);`,
    `  }`,
    '',
    `  /** Runs a read of your own on its table (exports, bulk actions, search). */`,
    `  query<T>(read: (db: Database) => Promise<T>) {`,
    `    return read(this.db);`,
    `  }`,
    '',
    `  /** Changes one; the audit entry holds what changed, from → to. */`,
    `  async update(by: Principal, row: ${S}, dto: Update${S}Dto, ip?: string, { restoredFrom }: { restoredFrom?: number } = {}) {`,
    `    const changes = await this.lifecycle.values(dto, 'update');`,
    `    if (Object.keys(changes).length === 0) {`,
    `      return row; // nothing to change`,
    `    }`,
    `    // Business logic: what a change must respect, here.`,
    `    return inTransaction(this.txHost, async (tx) => {`,
    `      const [updated] = await tx.update(${table}).set(changes).where(eq(${table}.id, row.id)).returning()${uniques.length ? '.catch(taken)' : ''};`,
    `      await this.lifecycle.updated(tx, { before: row, after: updated!, by, restoredFrom });`,
    `      await this.audit.recordChange(by, ${t.SINGULAR}_RESOURCE, { action: 'updated', id: row.id, before: recordView(${t.SINGULAR}, row), after: recordView(${t.SINGULAR}, updated!) }, tx, ip);`,
    `      return updated!;`,
    `    });`,
    `  }`,
    '',
    ...(softDelete
      ? [
          `  /** To the recycle bin (soft delete): hidden everywhere, restorable until purged. */`,
          `  async delete(by: Principal, row: ${S}, ip?: string) {`,
          `    await inTransaction(this.txHost, async (tx) => {`,
          `      await tx.update(${table}).set({ deletedAt: new Date(), deletedBy: principalKey(by) }).where(eq(${table}.id, row.id));`,
          `      await this.audit.recordChange(by, ${t.SINGULAR}_RESOURCE, { action: 'deleted', id: row.id, before: recordView(${t.SINGULAR}, row) }, tx, ip);`,
          `    });`,
          `  }`,
          '',
          `  /** Out of the recycle bin. */`,
          `  async restore(by: Principal, row: ${S}, ip?: string) {`,
          `    return inTransaction(this.txHost, async (tx) => {`,
          `      const [restored] = await tx.update(${table}).set({ deletedAt: null, deletedBy: null }).where(eq(${table}.id, row.id)).returning()${uniques.length ? '.catch(taken)' : ''};`,
          `      await this.audit.recordChange(by, ${t.SINGULAR}_RESOURCE, { action: 'restored', id: row.id, after: recordView(${t.SINGULAR}, restored!) }, tx, ip);`,
          `      return restored!;`,
          `    });`,
          `  }`,
        ]
      : [
          `  /** Deletes one for good. */`,
          `  async delete(by: Principal, row: ${S}, ip?: string) {`,
          `    await inTransaction(this.txHost, async (tx) => {`,
          `      await tx.delete(${table}).where(eq(${table}.id, row.id));`,
          `      await this.audit.recordChange(by, ${t.SINGULAR}_RESOURCE, { action: 'deleted', id: row.id, before: recordView(${t.SINGULAR}, row) }, tx, ip);`,
          `    });`,
          `  }`,
        ]),
    `}`,
    ...(uniques.length
      ? [
          '',
          `/** A unique field's value another one has already: a 409, not a 500. */`,
          `function taken(error: unknown): never {`,
          `  if (pgErrorCode(error) === UNIQUE_VIOLATION) {`,
          `    throw new ConflictException({ code: '${lowerFirst(S)}_taken', message: '${pascalOf(t.aNoun)} with this ${uniques.map((f) => f.name).join(' or ')} exists already.' });`,
          `  }`,
          `  throw error;`,
          `}`,
        ]
      : []),
  ].join('\n');
}

export function controller({ t, fields, softDelete }) {
  const S = t.Singular;
  const svc = t.pluralCamel;
  const uniques = fields.filter((f) => f.unique);
  return [
    `import { Body, Controller, Delete, ForbiddenException, Get, Headers, HttpCode, HttpStatus, Ip, Param, ParseUUIDPipe, Patch, Post, Query } from '@nestjs/common';`,
    `import { CurrentUser } from '@nestjs/authentication';`,
    `import { AuthorizationService, Can } from '@nestjs/authorization';`,
    `import { Idempotent } from '@nestjs/idempotency';`,
    `import { ApiBadRequestResponse, ApiBearerAuth, ApiConflictResponse, ApiCookieAuth, ApiCreatedResponse, ApiForbiddenResponse, ApiHeader, ApiNoContentResponse, ApiNotFoundResponse, ApiOkResponse, ApiOperation, ApiPreconditionFailedResponse, ApiTags, ApiUnauthorizedResponse, ApiUnprocessableEntityResponse } from '@nestjs/swagger';`,
    `import { and } from 'drizzle-orm';`,
    `import { assertUnchanged, Etag, ifMatchHeader, ifNoneMatchHeader } from '../../core/http/etag.js';`,
    `import { ApiListQuery } from '../../core/http/list-docs.js';`,
    `import { pageSchema } from '../../core/http/pagination.js';`,
    `import { AccessService } from '../../iam/access/access.service.js';`,
    `import type { RequestPrincipal } from '../../iam/auth/principal.js';`,
    `import { idempotencyKeyHeader } from '../../platform/idempotency/idempotency.openapi.js';`,
    `import { principalScope } from '../../platform/idempotency/idempotency.scopes.js';`,
    `import { recordListDocs, sentFields } from '../../platform/records/record.js';`,
    `import { RecordPresenter } from '../../platform/records/record-contract.js';`,
    `import { ${t.SINGULAR}_LIST } from './${t.singular}.list.js';`,
    `import { ${t.SINGULAR} } from './${t.singular}.record.js';`,
    `import { ${S}Policy } from './${t.singular}.policy.js';`,
    `import { type Create${S}Dto, type ${S}, ${t.SINGULAR}_SCHEMAS, type Update${S}Dto } from './${t.singular}.schemas.js';`,
    `import { ${t.Plural}Service } from './${t.plural}.service.js';`,
    '',
    `const SCHEMAS = ${t.SINGULAR}_SCHEMAS;`,
    '',
    `/**`,
    ` * ${pascalOf(t.nouns)}: the HTTP routes, nothing else (${t.plural}.service.ts does the work).`,
    ` * The capabilities' routes (tags, comments…) come from ${t.singular}.record.ts (${t.plural}.module.ts).`,
    ` */`,
    `@ApiTags('${t.plural}')`,
    `@ApiBearerAuth('api-key')`,
    `@ApiCookieAuth('user-session')`,
    `@ApiUnauthorizedResponse({ description: 'No valid API key or session.' })`,
    `@ApiForbiddenResponse({ description: 'Not allowed by your permissions.' })`,
    `@Controller('${t.plural}')`,
    `export class ${t.Plural}Controller {`,
    `  constructor(`,
    `    private readonly ${svc}: ${t.Plural}Service,`,
    `    private readonly access: AccessService,`,
    `    private readonly authorization: AuthorizationService,`,
    `    private readonly presenter: RecordPresenter,`,
    `  ) {}`,
    '',
    `  @Post()`,
    `  // A retry with the same key gets the first answer instead of a second record.`,
    `  @Idempotent({ scope: principalScope })`,
    `  @Can(${S}Policy, 'create')`,
    `  @ApiOperation({ summary: 'Create ${t.aNoun}', description: 'Send a new Idempotency-Key per record and the same one on every retry. Audited.' })`,
    `  @ApiHeader(idempotencyKeyHeader(true))`,
    `  @ApiCreatedResponse({ standardSchema: SCHEMAS.response })`,
    `  @ApiBadRequestResponse({ description: 'The body fails the schema, or the Idempotency-Key is missing.' })`,
    `  @ApiConflictResponse({ description: 'A request with this Idempotency-Key is still running${uniques.length ? `, or ${t.aNoun} with this ${uniques.map((f) => f.name).join(' or ')} exists (${lowerFirst(S)}_taken)` : ''}.' })`,
    `  @ApiUnprocessableEntityResponse({ description: 'This Idempotency-Key was used for a different request.' })`,
    `  async create(@CurrentUser() user: RequestPrincipal, @Body({ schema: SCHEMAS.create }) dto: Create${S}Dto) {`,
    `    await this.assertFields(user, 'create', dto);`,
    `    return this.presenter.one(user, await this.${svc}.create(user, dto));`,
    `  }`,
    '',
    `  /** Only those the caller may read: filtered in the query, not after. */`,
    `  @Get()`,
    `  @Etag()`,
    `  @Can.Anyone()`,
    `  @ApiOperation({ summary: 'The ${t.nouns} you may read, newest first', description: 'Filter flat or with \`filter\`, sort with \`sort\`, pick fields with \`fields\`; each parameter lists what it takes.' })`,
    `  @ApiOkResponse({ standardSchema: pageSchema(SCHEMAS.response) })`,
    `  @ApiListQuery(${t.SINGULAR}_LIST, recordListDocs(${t.SINGULAR}))`,
    `  async list(@CurrentUser() user: RequestPrincipal, @Query() raw: Record<string, unknown>) {`,
    `    // The list with the custom fields defined now (custom): validated per request.`,
    `    const list = await this.presenter.list(${t.SINGULAR}_LIST);`,
    `    const query = list.parse(raw);`,
    `    const page = await this.${svc}.findPage(`,
    `      and(`,
    softDelete
      ? `        // The recycle bin (?deleted=true) is for those who may restore.\n        await this.access.sqlFilter(user, '${S}', query.deleted ? 'restore' : 'read', { deleted: query.deleted === true }),`
      : `        await this.access.sqlFilter(user, '${S}', 'read'),`,
    `        list.where(query),`,
    `      ),`,
    `      query,`,
    `      list.sortSelect(query),`,
    `    );`,
    `    return list.pick({ ...page, items: await this.presenter.many(user, page.items) }, query);`,
    `  }`,
    '',
    `  @Get(':id')`,
    `  @Etag()`,
    `  @Can.Anyone() // Checked below, on the record itself.`,
    `  @ApiOperation({ summary: 'One ${t.noun}', description: 'With an ETag: If-None-Match gets 304 while unchanged; If-Match on a write refuses it if it changed.' })`,
    `  @ApiHeader(ifNoneMatchHeader())`,
    `  @ApiOkResponse({ standardSchema: SCHEMAS.response })`,
    `  @ApiNotFoundResponse()`,
    `  async get(@CurrentUser() user: RequestPrincipal, @Param('id', ParseUUIDPipe) id: string) {`,
    `    const row = await this.${svc}.findOne(id);`,
    `    await this.authorization.authorize(${S}Policy, 'read', user, row);`,
    `    return this.presenter.one(user, row);`,
    `  }`,
    '',
    `  @Patch(':id')`,
    `  @Etag()`,
    `  @Can.Anyone() // Checked below, on the record and on each field.`,
    `  @ApiOperation({ summary: 'Change ${t.aNoun}: only what is sent changes', description: 'With If-Match, refused (412) if it changed since you read it. Audited with what changed.' })`,
    `  @ApiHeader(ifMatchHeader())`,
    `  @ApiOkResponse({ standardSchema: SCHEMAS.response })`,
    `  @ApiNotFoundResponse()`,
    `  @ApiPreconditionFailedResponse({ description: 'It changed since you read it (precondition_failed).' })`,
    `  async update(`,
    `    @CurrentUser() user: RequestPrincipal,`,
    `    @Param('id', ParseUUIDPipe) id: string,`,
    `    @Body({ schema: SCHEMAS.update }) dto: Update${S}Dto,`,
    `    @Headers('if-match') ifMatch: string | undefined,`,
    `    @Ip() ip: string,`,
    `  ) {`,
    `    const row = await this.${svc}.findOne(id);`,
    `    await this.authorization.authorize(${S}Policy, 'update', user, row);`,
    `    assertUnchanged(ifMatch, await this.presenter.one(user, row));`,
    `    await this.assertFields(user, 'update', dto, row);`,
    `    return this.presenter.one(user, await this.${svc}.update(user, row, dto, ip));`,
    `  }`,
    ...(softDelete
      ? [
          '',
          `  @Post(':id/restore')`,
          `  @HttpCode(HttpStatus.OK)`,
          `  @Can.Anyone() // Checked below, on the record itself.`,
          `  @ApiOperation({ summary: 'Restore ${t.aNoun} from the recycle bin', description: 'Until the purge (SOFT_DELETE_RETENTION_DAYS after deleting it).' })`,
          `  @ApiOkResponse({ standardSchema: SCHEMAS.response })`,
          `  @ApiNotFoundResponse({ description: 'Not in the recycle bin (or purged).' })`,
          `  async restore(@CurrentUser() user: RequestPrincipal, @Param('id', ParseUUIDPipe) id: string, @Ip() ip: string) {`,
          `    const row = await this.${svc}.findOne(id, undefined, { deleted: true });`,
          `    await this.authorization.authorize(${S}Policy, 'restore', user, row);`,
          `    return this.presenter.one(user, await this.${svc}.restore(user, row, ip));`,
          `  }`,
        ]
      : []),
    '',
    `  @Delete(':id')`,
    `  @HttpCode(HttpStatus.NO_CONTENT)`,
    `  @Can.Anyone() // Checked below, on the record itself.`,
    `  @ApiOperation({ summary: 'Delete ${t.aNoun}${softDelete ? ' (to the recycle bin)' : ''}'${softDelete ? `, description: 'POST /v1/${t.plural}/{id}/restore brings it back until it is purged.'` : ''} })`,
    `  @ApiHeader(ifMatchHeader())`,
    `  @ApiNoContentResponse()`,
    `  @ApiNotFoundResponse()`,
    `  @ApiPreconditionFailedResponse({ description: 'It changed since you read it (precondition_failed).' })`,
    `  async delete(`,
    `    @CurrentUser() user: RequestPrincipal,`,
    `    @Param('id', ParseUUIDPipe) id: string,`,
    `    @Headers('if-match') ifMatch: string | undefined,`,
    `    @Ip() ip: string,`,
    `  ) {`,
    `    const row = await this.${svc}.findOne(id);`,
    `    await this.authorization.authorize(${S}Policy, 'delete', user, row);`,
    `    assertUnchanged(ifMatch, await this.presenter.one(user, row));`,
    `    await this.${svc}.delete(user, row, ip);`,
    `  }`,
    '',
    `  /** Field-level: a 403 naming the fields this caller may not set. */`,
    `  private async assertFields(user: RequestPrincipal, action: string, dto: object, row?: ${S}) {`,
    `    const forbidden = await this.access.forbiddenFields(user, action, '${S}', sentFields(dto), row);`,
    `    if (forbidden.length) {`,
    `      throw new ForbiddenException({ code: 'field_forbidden', message: \`You may not set: \${forbidden.join(', ')}.\`, fields: forbidden });`,
    `    }`,
    `  }`,
    `}`,
  ].join('\n');
}

