/**
 * Notes: the writes and the reads. Each write, its audit entry and what its
 * capabilities do (RecordLifecycle: number, watchers, revisions) commit in one transaction;
 * what note.record.ts decides (the recycle bin, organizational units) RecordStore does.
 * Generated by `pnpm feature:add` (tools/feature): the business logic goes where the comments say "Business logic":
 * a note's publication workflow, its webhooks and notifications, the batch
 * writes an import group uses, and the example sender's request to publish.
 */
@Injectable()
export class NotesService {
  constructor(
    private readonly txHost: TransactionHost<DrizzleTransactions>,
    private readonly audit: AuditService,
    private readonly lifecycle: RecordLifecycle,
    private readonly records: RecordStore,
    private readonly workflowClient: WorkflowClient,
    private readonly webhooks: Webhooks<Transaction>,
    private readonly publisher: NotePublisher,
    private readonly customFields: CustomFieldsService,
    private readonly access: AccessService,
    private readonly notifications: NotificationsService,
    private readonly subscriptions: SubscriptionsService,
    private readonly tenancy: Tenancy,
    private readonly system: SystemContext,
    private readonly batch: NoteBatch,
    incomingEvents: IncomingEventHandlers,
    retention: RetentionRegistry,
  ) {
    // Notes are purged after the days a tenant sets (off until it turns the rule on).
    retention.register({
      name: 'note',
      label: 'Notes',
      subject: 'Note',
      table: notes,
      ageColumn: notes.createdAt,
      action: 'purge',
      defaultDays: 730,
      minDays: 30,
    });
    // A tenant's own sender (docs/webhooks-and-realtime.md): the tenant is the
    // sender's, so the event names only the note, and the request already runs in it.
    incomingEvents.register(
      'note.publish-requested',
      {
        description: 'Request publication of an existing note of the tenant.',
        dataSchema: z.object({ noteId: z.uuid() }),
        example: { noteId: '00000000-0000-4000-8000-000000000001' },
        delivery:
          'Deduplicated by the webhook-id: a redelivery is answered 200 and not run again. 200 once the request is recorded; an unknown note is a 404, which the sender may retry.',
      },
      ({ webhook }) => {
        const { noteId } = webhook.payload.data as { noteId: string };
        return inTransaction(this.txHost, async (tx) =>
          webhook.processInTransaction(tx, () =>
            this.requestPublish(tx, noteId, webhook.id),
          ),
        );
      },
    );
  }

  /** The current transaction, or the database outside one (core/database/transactions.ts). */
  private get db() {
    return database(this.txHost);
  }

  /**
   * A new draft of `owner`'s. `by` is who acts, when not the owner: the
   * demo seed (src/demo) writes its users' notes as the system principal,
   * so the audit entry and the first revision name it, and the note is
   * still theirs.
   */
  async create(
    owner: Principal,
    dto: CreateNoteDto,
    { by = owner }: { by?: Principal } = {},
  ): Promise<Note> {
    // Business logic: check or derive values here, before the transaction.
    // The body as columns; custom values checked against their fields (RecordLifecycle).
    const values = await this.lifecycle.values(dto, 'create');
    const note = await inTransaction(this.txHost, async (tx) => {
      const [row] = await tx
        .insert(notes)
        .values({
          // Its owner, and with units the owner's unit.
          ...(await this.records.owner(owner, tx)),
          // Its number (numbered), when the record takes one: in the body's naming series, else the default.
          ...(await this.lifecycle.creating(tx, dto)),
          ...values,
          // A new note is a draft: the publication workflow publishes it.
          status: 'draft',
        } as typeof notes.$inferInsert)
        .returning();
      await this.lifecycle.created(tx, { row: row!, owner, by });
      // Business logic: what else happens with it, in this transaction (events, notifications).
      // Same transaction: the publication and the note.created webhook
      // exist if and only if the note does.
      await this.workflowClient.start(
        NotePublicationWorkflow,
        { noteId: row!.id, tenantId: row!.tenantId },
        { id: publicationId(row!.id), transaction: tx },
      );
      await this.publisher.dispatch(tx, 'note.created', row!);
      await this.audit.recordChange(
        by,
        NOTE_RESOURCE,
        { action: 'created', id: row!.id, after: recordView(NOTE, row!) },
        tx,
      );
      return row!;
    });
    this.webhooks.notify(); // deliver now instead of at the next poll
    return note;
  }

  /** Creates one import group under one transaction and grouped side effects (NoteBatch). */
  createMany(
    owner: Principal,
    dtos: readonly NoteInput[],
    options?: { by?: Principal },
  ) {
    return this.batch.createMany(owner, dtos, options);
  }

  /** One, or a 404 (with `deleted`, one in the recycle bin; with `visibleTo`, only one that principal may read: else the same 404). */
  findOne(
    id: string,
    db: Database | Transaction = this.db,
    options: { deleted?: boolean; visibleTo?: Principal } = {},
  ) {
    return this.records.findOne<Note>(id, db, options);
  }

  /**
   * A page of those `user` may read matching the list's query, newest first: the read
   * filter and the query's `where` compose in RecordStore, so the controller builds no predicate.
   */
  findPage(user: Principal, list: List, query: ListQuery) {
    return this.records.findPage<Note>(user, list, query);
  }

  /** Counts the live notes `user` may read by UTC week (from a Monday) in one grouped query. */
  async weeklyCounts(user: Principal, from: Date, weeks: number) {
    const to = new Date(from.getTime() + weeks * 7 * 24 * 60 * 60 * 1000);
    const list = await this.customFields.extendList(NOTE_LIST, 'Note');
    const filters = list.parse({
      'createdAt.gte': from.toISOString(),
      'createdAt.lt': to.toISOString(),
    });
    await this.access.assertQueryFields(user, 'Note', filters);
    const where = and(
      await this.access.sqlFilter(user, 'Note', 'read'),
      list.where(filters),
    );
    const week = sql<string>`to_char(
      date_trunc('week', ${notes.createdAt} at time zone 'UTC'),
      'YYYY-MM-DD'
    )`;
    const rows = await this.db
      .select({ week, count: sql<number>`count(*)::int` })
      .from(notes)
      .where(inTenant(notes.tenantId, where))
      .groupBy(week)
      .orderBy(week);
    const counts = new Map(rows.map((row) => [row.week, row.count]));
    const millisecondsPerWeek = 7 * 24 * 60 * 60 * 1000;
    return Array.from({ length: weeks }, (_, index) => {
      const weekStart = new Date(from.getTime() + index * millisecondsPerWeek)
        .toISOString()
        .slice(0, 10);
      return { week: weekStart, count: counts.get(weekStart) ?? 0 };
    });
  }

  /** Runs a read of your own on its table (exports, bulk actions, search). */
  query<T>(read: (db: Database) => Promise<T>) {
    return read(this.db);
  }

  /** Changes one; the audit entry holds what changed, from → to. */
  async update(
    by: Principal,
    row: Pick<Note, 'id'>,
    dto: UpdateNoteDto,
    ip?: string,
    {
      restoredFrom,
      prepareCurrent,
      assertCurrent,
    }: {
      restoredFrom?: number;
      prepareCurrent?: (
        current: Note,
      ) => Promise<UpdateNoteDto> | UpdateNoteDto;
      assertCurrent?: (
        current: Note,
        dto: UpdateNoteDto,
      ) => Promise<void> | void;
    } = {},
  ) {
    const changes = prepareCurrent
      ? undefined
      : await this.lifecycle.values(dto, 'update');
    if (changes && Object.keys(changes).length === 0 && !assertCurrent) {
      return row as Note; // nothing to change
    }
    // Business logic: what a change must respect, here.
    const updated = await inTransaction(this.txHost, async (tx) => {
      if (prepareCurrent || (changes && Object.keys(changes).length > 0))
        await this.lifecycle.assertNotPending(row.id);
      const current = await this.records.lock<Note>(tx, row.id);
      const currentDto = prepareCurrent ? await prepareCurrent(current) : dto;
      const currentChanges =
        changes ?? (await this.lifecycle.values(currentDto, 'update'));
      await assertCurrent?.(current, currentDto);
      if (Object.keys(currentChanges).length === 0) return current;
      const [updated] = await tx
        .update(notes)
        .set(currentChanges)
        .where(eq(notes.id, row.id))
        .returning();
      await this.lifecycle.updated(tx, {
        before: current,
        after: updated!,
        by,
        restoredFrom,
      });
      // Whoever watches the note hears of it, but the one who changed it;
      // repeated changes collapse into one notification per note.
      await this.subscriptions.notifyWatchers(tx, {
        subject: 'Note',
        recordId: row.id,
        type: 'note.changed',
        data: { noteId: row.id, title: updated!.title, by: by.name },
        key: `note.changed:${row.id}`,
        link: `/notes/${row.id}`,
        except: by,
      });
      await this.audit.recordChange(
        by,
        NOTE_RESOURCE,
        {
          action: 'updated',
          id: row.id,
          before: recordView(NOTE, current),
          after: recordView(NOTE, updated!),
        },
        tx,
        ip,
      );
      return updated!;
    });
    this.notifications.deliverNow();
    return updated;
  }

  /** Applies a group of edits (an import matched to notes) in one UPDATE (NoteBatch). */
  updateMany(
    by: Principal,
    matches: readonly { noteId: string; dto: Partial<NoteInput> }[],
    ip?: string,
  ) {
    return this.batch.updateMany(by, matches, ip);
  }

  /** Deletes one: to the recycle bin (restorable until purged) when it has one, else for good. */
  async delete(
    by: Principal,
    row: Note,
    ip?: string,
    assertCurrent?: (current: Note) => Promise<void> | void,
  ) {
    // Business logic: what a delete must respect, here.
    await inTransaction(this.txHost, async (tx) => {
      await this.lifecycle.assertNotPending(row.id);
      const current = await this.records.lock<Note>(tx, row.id);
      await assertCurrent?.(current);
      await this.records.delete(tx, by, current);
      await this.publisher.dispatch(tx, 'note.deleted', current);
      if (current.ownerId !== principalKey(by)) {
        // Someone else's doing: the owner is told (and can't switch it off).
        await this.notifications.notify(tx, {
          type: 'note.deleted',
          to: current.ownerId,
          data: { noteId: current.id, title: current.title, by: by.name },
        });
      }
      await this.audit.recordChange(
        by,
        NOTE_RESOURCE,
        { action: 'deleted', id: row.id, before: recordView(NOTE, current) },
        tx,
        ip,
      );
    });
    // A draft's publication would find nothing to publish: stop it.
    await this.workflowClient.cancel(publicationId(row.id), 'Note deleted.');
    this.webhooks.notify();
    this.notifications.deliverNow();
  }

  /** Out of the recycle bin (POST /v1/notes/{id}/restore, a bulk restore). A draft's publication was cancelled on delete: publish it again by hand. */
  async restore(by: Principal, row: Note, ip?: string) {
    return inTransaction(this.txHost, async (tx) => {
      const restored = await this.records.restore<Note>(tx, row);
      await this.audit.recordChange(
        by,
        NOTE_RESOURCE,
        { action: 'restored', id: row.id, after: recordView(NOTE, restored) },
        tx,
        ip,
      );
      return restored;
    });
  }

  /**
   * An incoming webhook asks for a publication: recorded with the event, in
   * one transaction, so a redelivered event changes nothing (`duplicate`).
   * The route is public (the sender signs it), so it has no tenant: the
   * event names the note's tenant, and the transaction runs in it (an
   * unknown tenant, or a note of another, is a 404 like an unknown note).
   */
  publishFromWebhook(
    webhook: IncomingWebhook<{ data: { noteId: string; tenantId: string } }>,
  ) {
    const { noteId, tenantId } = webhook.payload.data;
    return this.tenancy.run(tenantId.toLowerCase(), () =>
      inTransaction(this.txHost, async (tx) =>
        webhook.processInTransaction(tx, () =>
          this.requestPublish(tx, noteId, webhook.id),
        ),
      ),
    );
  }

  async requestPublish(tx: Transaction, noteId: string, eventId: string) {
    const note = await this.findOne(noteId, tx); // 404 before anything is recorded
    let offset = 0;
    for (;;) {
      const instances = await this.workflowClient.list({
        workflow: 'note-batch-publication',
        status: ['pending', 'running', 'suspended'],
        limit: 100,
        offset,
      });
      const batch = instances.find((instance) => {
        const input = instance.input as { noteIds?: unknown };
        return Array.isArray(input.noteIds) && input.noteIds.includes(noteId);
      });
      if (batch) {
        // A grouped workflow has no individual publication wait; publish this requested note directly, and let the group's later UPDATE skip it.
        await this.system.run(
          NOTE_PUBLICATION_JOB,
          (system) => this.publisher.publish(noteId, system),
          { transaction: false },
        );
        return;
      }
      if (instances.length < 100) break;
      offset += instances.length;
    }
    await this.workflowClient.signal(
      publishNow,
      { eventId, tenantId: note.tenantId },
      { key: noteId, transaction: tx },
    );
  }
}
